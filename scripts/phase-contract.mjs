check('retired V6 components removed', retired.every(name => !exists(`src/components/${name}`)))
check('retired standalone sections absent from App', !/(<ArchiveGallery|<AwardsArchive|<EngineeringProof|<IndonesiaMission|<MemoryCore|<MissionOrbit|<RobotEvolution)/.test(app))
check('retired Three/R3F dependencies removed', !pkg.dependencies?.['@react-three/fiber'] && !pkg.dependencies?.['@react-three/drei'] && !pkg.dependencies?.['@react-three/postprocessing'] && !pkg.dependencies?.three)
