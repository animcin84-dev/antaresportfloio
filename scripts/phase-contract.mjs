const v7Components = ['MemorySpine.jsx','ContinuitySection.jsx','MemoryTimeline.jsx','MachineChapter.jsx','MissionChapter.jsx','FlightRecorder.jsx','ArchiveDrawer.jsx','PeopleChapter.jsx']
for (const name of v7Components) check(`V7 component exists: ${name}`, exists(`src/components/${name}`))
